const meta = (slug: string) => {
  const item = NEWS.find((news) => news.slug === slug);
  if (!item) throw new Error(`news item not found: ${slug}`);
  return {
    slug,
    title: item.title.join(" "),
    tag: item.tag,
    date: `${item.date} ${item.datetime.slice(0, 4)}`,
    datetime: item.datetime,
    author: "Редакция ВАС СТРОЙ",
    cover: item.src,
  };
};

