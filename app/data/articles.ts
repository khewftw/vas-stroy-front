export const articleBySlug = (slug: string) => ARTICLES.find((article) => article.slug === slug);

export const readingMinutes = (article: Article) => {
  const words = article.blocks
    .map((block) => {
      switch (block.type) {
        case "intro":
        case "p":
        case "h3":
        case "quote":
        case "callout":
          return block.type === "callout" ? `${block.title} ${block.text}` : "text" in block ? block.text : "";
        case "list":
        case "checklist":
          return block.items.join(" ");
        case "accordion":
          return block.items.map((item) => `${item.q} ${item.a}`).join(" ");
        default:
          return "";
      }
    })
    .join(" ")
    .split(/\s+/)
    .filter(Boolean).length;
  return Math.max(2, Math.round(words / 180));
};
