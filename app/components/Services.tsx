export default function Services() {
  const base = useId();
  const [open, setOpen] = useState<string | null>(SERVICES[0].id);
  const sectionRef = useRef<HTMLElement>(null);

  // line the title column up with the first link of the header menu
  useEffect(() => {
    const section = sectionRef.current;
    if (!section) return;
    const sync = () => {
      const shell = section.querySelector<HTMLElement>(".shell");
      const link = document.querySelector<HTMLElement>(".site-nav a");
      if (!shell || !link) return;
      const offset = link.getBoundingClientRect().left - shell.getBoundingClientRect().left;
      if (offset > 0) section.style.setProperty("--nav-x", `${Math.round(offset)}px`);
    };
    sync();
    window.addEventListener("resize", sync);
    document.fonts?.ready.then(sync);
    return () => window.removeEventListener("resize", sync);
  }, []);

  return (
    <section ref={sectionRef} className="services" id="services" aria-labelledby="services-title">
      <div className="shell">
        <div className="section-head" data-reveal data-reveal-stagger>
          <h2 id="services-title">Оказываемые услуги</h2>
          <p className="section-lead">
            Внутренняя отделка и ремонт коммерческих, общественных и государственных объектов: от черновых работ до чистовой сдачи. Выберите направление, чтобы увидеть полный состав работ.
          </p>
        </div>
        <ul className="svc-list">
          {SERVICES.map((s, i) => {
            const isOpen = open === s.id;
            return (
              <li key={s.id} className={`svc${isOpen ? " is-open" : ""}`}>
                <h3>
                  <button type="button" aria-expanded={isOpen} aria-controls={`${base}-${s.id}`} onClick={() => setOpen(isOpen ? null : s.id)}>
                    <span className="svc-num">{String(i + 1).padStart(2, "0")}</span>
                    <span className="svc-title">{s.title}</span>
                    <span className="svc-sign" aria-hidden="true" />
                  </button>
                </h3>
                <div id={`${base}-${s.id}`} className="svc-panel" role="region" aria-label={s.title}>
                  <div>
                    <p>{s.text}</p>
                    <ul>
                      {s.items.map((item) => (
                        <li key={item}>{item}</li>
                      ))}
                    </ul>
                    <BookButton
                      className="svc-apply"
                      offer={{ title: "Оставить заявку", meta: `Услуга: ${s.title}`, submitLabel: "Оставить заявку", source: `service: ${s.title}` }}
                    >
                      <span>Оставить заявку</span>
                      <span className="svc-apply-arrow" aria-hidden="true">→</span>
                    </BookButton>
                  </div>
                </div>
              </li>
            );
          })}
        </ul>
        <div className="svc-cta">
          <h3>Не нашли то, что нужно? Закажите звонок инженеру!</h3>
          <p>Ведущий инженер компании ВАС СТРОЙ поможет с любым вопросом и максимально оперативно отправит смету.</p>
          <BookButton className="cta-line" offer="call">
            <span>Заказать звонок инженера</span>
            <span className="cta-line-arrow" aria-hidden="true">→</span>
          </BookButton>
        </div>
      </div>
    </section>
  );
}
